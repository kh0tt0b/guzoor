export function pick(language: Language, en: string, ar?: string): string {
  if (language === 'ar' && ar) return ar
  return en
}

type LeafNode = { en: string; ar: string }
type Namespace = Record<string, LeafNode>

export function translate(
  language: Language,
  namespace: keyof typeof translations,
  key: string,
): string {
  const ns = translations[namespace] as unknown as Namespace
  const entry = ns[key]
  if (!entry) return key
  return entry[language]
}
